function findFile(pattern) {
  const files = fs.existsSync(SRC) ? fs.readdirSync(SRC).filter((f) => f.endsWith('.txt')) : [];
  return files.find((f) => pattern.test(f));
}

function load(file) {
  const lines = fs
    .readFileSync(path.join(SRC, file), 'utf8')
    .split(/\r?\n/)
    .filter((l) => !/THE GAZETTE OF INDIA|भारत का राज/.test(l)) // page header
    .filter((l) => !/^\s*\d{1,3}\s*$/.test(l)); // akela number (page no / footnote no)
  return norm(lines.join(' '));
}

function cut(src, c) {
  let start = 0;
  if (c.after) {
    start = src.indexOf(norm(c.after));
    if (start < 0) throw new Error(`'after' nahi mila: ${c.after}`);
  }
  const f = src.indexOf(norm(c.from), start);
  if (f < 0) throw new Error(`'from' nahi mila: ${c.from}`);
  const t = src.indexOf(norm(c.to), f);
  if (t < 0) throw new Error(`'to' nahi mila: ${c.to}`);
  let text = src.slice(f, t + norm(c.to).length);
  for (const [re, rep] of c.fixes || []) text = text.replace(new RegExp(re), rep);
  return text.trim();
}

fs.mkdirSync(OUT, { recursive: true });
const seen = new Set();
let failed = false;

for (const d of DOCS) {
  const outPath = path.join(OUT, d.out);
  const file = findFile(d.pattern);
  const skip = (msg) => {
    if (d.required) {
      failed = true;
      console.error(`FAIL ${d.name}: ${msg}`);
    } else {
      console.warn(`SKIP ${d.name}: ${msg}`);
    }
    if (fs.existsSync(outPath)) fs.rmSync(outPath); // purani/adhoori file seed na ho
  };

  if (!file) {
    skip(`data/sources/ me iski .txt file nahi mili (naam me '${d.pattern.source}' hona chahiye)`);
    continue;
  }
  const src = load(file);
  if (!src.includes(norm(d.marker))) {
    skip(`${file} me ye document nahi hai (phrase '${d.marker}' nahi mila). Galat document paste hua hai.`);
    continue;
  }

  const clauses = [];
  for (const c of d.clauses) {
    try {
      const text = cut(src, c);
      if (text.length < 20 || text.length > 900) throw new Error(`text ki lambai ajeeb hai (${text.length})`);
      if (seen.has(c.id)) throw new Error('id repeat');
      seen.add(c.id);
      clauses.push({ id: c.id, text });
      console.log(`OK   ${c.id}  [${text.slice(0, 50)} ... ${text.slice(-30)}]`);
    } catch (e) {
      failed = true;
      console.error(`FAIL ${file} ${c.id}: ${e.message}`);
    }
  }
  if (clauses.length) {
    fs.writeFileSync(
      outPath,
      JSON.stringify({ name: d.name, source: d.source, version: d.version, clauses }, null, 2),
    );
  }
}
process.exit(failed ? 1 : 0);