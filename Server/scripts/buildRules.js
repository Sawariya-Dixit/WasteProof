import fs from 'node:fs';
import path from 'node:path';

const SRC = path.resolve('data/sources');
const OUT = path.resolve('data/rules');
const norm = (s) =>
  String(s)
    .replace(/[\u2018\u2019]/g, "'")
    .replace(/[\u201C\u201D]/g, '"')
    .replace(/[\u2013\u2014]/g, '-')
    .replace(/\s+/g, ' ')
    .trim();

// pattern = file ke naam me ye ho; marker = andar ye phrase hona chahiye (sahi document ki pehchaan)
// required=false: file na mile / galat ho to sirf warning, baaki chalta rahe.
